/** Image audit: checks DB image records against files on disk and writes docs/IMAGE_AUDIT.md (use --write). */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { eq } from "drizzle-orm";
import { db } from "../src/server/db";
import { productImages, products } from "../src/server/db/schema";

async function main() {
  const write = process.argv.includes("--write");
  const manifest = JSON.parse(fs.readFileSync("data/image-manifest.json", "utf8")) as { sku: string; board: string; boardIndex: number; boardLabel: string; match: string }[];
  const mBySku = new Map(manifest.map((m) => [m.sku, m]));
  const rows = await db.select().from(products).orderBy(products.sku);
  const imgs = await db.select().from(productImages).where(eq(productImages.isPrimary, true));
  const byProduct = new Map(imgs.map((i) => [i.productId, i]));
  const problems: string[] = [];
  const counts = { uploaded: 0, sourced: 0, illustration: 0, missing: 0, similar: 0 };
  const lines: string[] = [];
  for (const p of rows) {
    const img = byProduct.get(p.id);
    if (!img) { counts.missing++; lines.push(`| ${p.sku} | ${p.name} | — | missing (placeholder shown) |`); continue; }
    if (img.url.startsWith("/products/")) {
      const f = path.join("public", img.url);
      if (!fs.existsSync(f)) problems.push(`${p.sku}: file missing ${img.url}`);
      else {
        const meta = await sharp(f).metadata();
        if (meta.format !== "webp" || (meta.width ?? 0) < 600) problems.push(`${p.sku}: unexpected image format/size (${meta.format} ${meta.width}x${meta.height})`);
      }
    }
    if (img.sourceType === "ORIGINAL_ILLUSTRATION") { counts.illustration++; problems.push(`${p.sku}: still uses a generated illustration`); }
    else if (img.sourceType === "ADMIN_UPLOAD") counts.uploaded++;
    else counts.sourced++;
    const m = mBySku.get(p.sku);
    if (m?.match === "similar") counts.similar++;
    lines.push(`| ${p.sku} | ${p.name} | ${img.url} | ${img.sourceType === "ADMIN_UPLOAD" ? "owner-supplied board" : img.sourceType.toLowerCase()} · ${img.licenseStatus.toLowerCase()} · ${img.verificationStatus.toLowerCase()}${m ? ` · board “${m.boardLabel}” (${m.match})` : ""} |`);
  }
  for (const m of manifest) if (!rows.some((p) => p.sku === m.sku)) problems.push(`manifest SKU not in DB: ${m.sku}`);
  console.log(`products: ${rows.length}`);
  console.log(`owner-supplied images: ${counts.uploaded} (of which name-similar rather than identical: ${counts.similar})`);
  console.log(`supplier/manufacturer/stock images: ${counts.sourced}`);
  console.log(`generated illustrations: ${counts.illustration}`);
  console.log(`missing (placeholder): ${counts.missing}`);
  if (write) {
    const md = `# Product image audit\n\nGenerated by \`npm run images:verify -- --write\`.\n\n| Measure | Count |\n|---|---|\n| Products | ${rows.length} |\n| Using owner-supplied images | ${counts.uploaded} |\n| …of which the board label is similar to, not identical with, the product name | ${counts.similar} |\n| Supplier / manufacturer / licensed stock images | ${counts.sourced} |\n| Generated illustrations | ${counts.illustration} |\n| Missing (neutral “Image coming soon” placeholder) | ${counts.missing} |\n\nAll owner-supplied images are cropped from the Code Crest catalogue boards supplied by the site owner. Permission status is recorded as *permitted* (supplied by the owner) and verification is *pending*: they are not supplier or manufacturer photographs and the origin of the underlying artwork is not documented.\n\n| SKU | Product | Image | Source / status |\n|---|---|---|---|\n${lines.join("\n")}\n`;
    fs.writeFileSync("docs/IMAGE_AUDIT.md", md);
    console.log("wrote docs/IMAGE_AUDIT.md");
  }
  if (problems.length) { console.error("PROBLEMS:\n" + problems.join("\n")); process.exit(1); }
  console.log("✓ image paths and records verified");
}
main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
